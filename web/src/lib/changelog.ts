export const CURRENT = CHANGELOG[0].version;
const SEEN_KEY = 'txq_seen_version';
export const hasUnseen = () => {
  try {
    return localStorage.getItem(SEEN_KEY) !== CURRENT;
  } catch {
    return false;
  }
};
export const markSeen = () => {
  try {
    localStorage.setItem(SEEN_KEY, CURRENT);
  } catch {
    /* ignore */
  }
};
